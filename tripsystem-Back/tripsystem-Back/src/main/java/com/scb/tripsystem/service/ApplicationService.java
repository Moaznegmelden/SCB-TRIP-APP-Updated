    // =========================================================
    // LINE MANAGER - APPROVE
    // =========================================================

    @Transactional
    public Application approveByManager(

            Long applicationId,
            Employee manager,
            String comments) {

        Application application =
                getApplicationById(
                        applicationId,
                        manager
                );


        // =====================================================
        // DIRECT MANAGER CHECK
        // =====================================================

        validateManagerOwnership(
                application,
                manager
        );


        // =====================================================
        // STATUS CHECK
        // =====================================================

        if (application.getStatus() == null ||
                !"PENDING_MANAGER".equals(
                        application
                                .getStatus()
                                .getStatusName())) {

            throw new RuntimeException(
                    "Application is not in PENDING_MANAGER status"
            );
        }


        // =====================================================
        // APPROVE
        // =====================================================

        application.setStatus(
                statusService.getByName(
                        "APPROVED_BY_MANAGER"
                )
        );


        Application saved =
                applicationRepository.save(
                        application
                );


        // =====================================================
        // APPROVAL HISTORY
        // =====================================================

        saveHistory(
                saved,
                manager,
                "LINE_MANAGER",
                "APPROVED",
                comments
        );


        return saved;
    }


