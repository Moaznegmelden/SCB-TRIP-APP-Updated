    // =========================================================
    // MANAGER OWNERSHIP VALIDATION
    // =========================================================

    private void validateManagerOwnership(

            Application application,
            Employee manager) {

        if (application == null ||
                application.getEmployee() == null) {

            throw new RuntimeException(
                    "Application employee information is missing"
            );
        }


        Employee applicationEmployee =
                application.getEmployee();


        if (applicationEmployee.getManager() == null) {

            throw new RuntimeException(
                    "This employee has no assigned manager"
            );
        }


        if (!applicationEmployee
                .getManager()
                .getEmployeeId()
                .equals(
                        manager.getEmployeeId()
                )) {

            throw new RuntimeException(
                    "You are not the manager of this employee"
            );
        }
    }


    // =========================================================
    // GET EMPLOYEE ROLE
    // =========================================================

    private String getEmployeeRole(
            Employee employee) {

        if (employee == null ||
                employee.getRole() == null) {

            return "";
        }

        return employee
                .getRole()
                .getRoleName();
    }



    // =========================================================
// LINE MANAGER - APPROVAL HISTORY
// =========================================================

    public List<ApprovalHistory> getManagerApprovalHistory(
            Employee manager) {

        return approvalHistoryRepository
                .findByActionBy_EmployeeIdAndRoleAtActionOrderByActionAtDesc(
                        manager.getEmployeeId(),
                        "LINE_MANAGER"
                );
    }


    // =========================================================
    // SAVE APPROVAL HISTORY
    // =========================================================

    private void saveHistory(

            Application application,

            Employee actionBy,

            String role,

            String action,

            String comments) {

        ApprovalHistory history =
                new ApprovalHistory();


        history.setApplication(
                application
        );


        history.setActionBy(
                actionBy
        );


        history.setRoleAtAction(
                role
        );


        history.setAction(
                action
        );


        history.setComments(
                comments
        );


        history.setActionAt(
                LocalDateTime.now()
        );


        approvalHistoryRepository.save(
                history
        );
    }
