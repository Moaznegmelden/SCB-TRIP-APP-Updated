    // =========================================================
    // EMPLOYEE - APPLY FOR TRIP
    // =========================================================

    @Transactional
    public Application applyForTrip(

            Long tripId,
            Long batchId,
            Employee employee,
            String transportType,
            String pickupPoint,
            Integer roomsRequested,
            BigDecimal totalPrice,
            List<ApplicationParticipant> participants) {

        Trip trip =
                tripService.getTripById(tripId);


        // =====================================================
        // PREVENT DUPLICATE APPLICATION
        // =====================================================

        if (applicationRepository
                .existsByEmployee_EmployeeIdAndTrip_TripId(
                        employee.getEmployeeId(),
                        tripId)) {

            throw new RuntimeException(
                    "Employee has already applied for this trip"
            );
        }


        // =====================================================
        // TRIP MUST BE ACTIVE
        // =====================================================

        if (trip.getStatus() == null ||
                !"ACTIVE".equals(
                        trip.getStatus().getStatusName())) {

            throw new RuntimeException(
                    "You can only apply to ACTIVE trips"
            );
        }


        // =====================================================
        // REGISTRATION PERIOD
        // =====================================================

        LocalDateTime now =
                LocalDateTime.now();

        if (trip.getRegistrationOpen() != null &&
                now.isBefore(
                        trip.getRegistrationOpen())) {

            throw new RuntimeException(
                    "Registration has not opened yet"
            );
        }

        if (trip.getRegistrationClose() != null &&
                now.isAfter(
                        trip.getRegistrationClose())) {

            throw new RuntimeException(
                    "Registration is closed for this trip"
            );
        }


        // =====================================================
        // BATCH
        // =====================================================

        Batch batch =
                batchRepository.findById(batchId)
                        .orElseThrow(() ->
                                new RuntimeException(
                                        "Batch not found"
                                )
                        );


        if (batch.getTrip() == null ||
                batch.getTrip().getTripId() == null ||
                !batch.getTrip()
                        .getTripId()
                        .equals(tripId)) {

            throw new RuntimeException(
                    "Batch does not belong to this trip"
            );
        }


        // =====================================================
        // CREATE APPLICATION
        //
        // createdAt is automatically generated by
        // @CreationTimestamp in Application entity.
        // We intentionally DO NOT take submission time
        // from Angular/frontend.
        // =====================================================

        Application application =
                new Application();

        application.setEmployee(
                employee
        );

        application.setTrip(
                trip
        );

        application.setBatch(
                batch
        );

        application.setTransportType(
                transportType
        );

        application.setPickupPoint(
                pickupPoint
        );

        application.setRoomsRequested(
                roomsRequested != null
                        ? roomsRequested
                        : 1
        );

        application.setTotalPrice(
                totalPrice
        );

        application.setStatus(
                statusService.getByName(
                        "PENDING_MANAGER"
                )
        );


        // =====================================================
        // PARTICIPANTS
        // =====================================================

        if (participants != null) {

            for (
                    ApplicationParticipant p
                    : participants
            ) {

                p.setApplication(
                        application
                );

                application
                        .getParticipants()
                        .add(p);
            }
        }


        // =====================================================
        // SAVE
        // =====================================================

        Application saved =
                applicationRepository.save(
                        application
                );


        // =====================================================
        // HISTORY
        // =====================================================

        saveHistory(
                saved,
                employee,
                "EMPLOYEE",
                "APPLIED",
                "Employee submitted application"
        );


        return saved;
    }


