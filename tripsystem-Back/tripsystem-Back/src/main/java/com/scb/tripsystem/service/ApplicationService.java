    // =========================================================
    // HR ADMIN - SELECTION
    // =========================================================

    @Transactional
    public void performSelection(

            Long tripId,
            String method,
            Employee hrUser) {


        // =====================================================
        // VALIDATE METHOD
        // =====================================================

        if (method == null ||
                (
                        !"FIFO".equalsIgnoreCase(method)
                                &&
                                !"RANDOM".equalsIgnoreCase(method)
                )) {

            throw new RuntimeException(
                    "Selection method must be FIFO or RANDOM"
            );
        }


        String selectionMethod =
                method.trim().toUpperCase();


        // =====================================================
        // GET CANDIDATES
        //
        // For FIFO we deliberately query the database ordered
        // by createdAt ASC.
        //
        // For RANDOM we load the normal candidates and shuffle.
        // =====================================================

        List<Application> candidates;

        if ("FIFO".equals(selectionMethod)) {

            candidates =
                    new ArrayList<>(
                            applicationRepository
                                    .findForFifoSelection(
                                            tripId,
                                            "APPROVED_BY_MANAGER"
                                    )
                    );

        } else {

            candidates =
                    new ArrayList<>(
                            getApplicationsReadyForSelection(
                                    tripId
                            )
                    );

            Collections.shuffle(
                    candidates
            );
        }


        if (candidates.isEmpty()) {

            throw new RuntimeException(
                    "No applications ready for selection"
            );
        }


        // =====================================================
        // VERIFY ALL APPLICATIONS BELONG TO THE TRIP
        // =====================================================

        for (Application app : candidates) {

            if (app.getTrip() == null ||
                    app.getTrip().getTripId() == null ||
                    !app.getTrip()
                            .getTripId()
                            .equals(tripId)) {

                throw new RuntimeException(
                        "Application does not belong to the selected trip"
                );
            }
        }


        // =====================================================
        // SET IN_SELECTION
        // =====================================================

        Status inSelectionStatus =
                statusService.getByName(
                        "IN_SELECTION"
                );


        for (Application app : candidates) {

            app.setStatus(
                    inSelectionStatus
            );

            app.setSelectionMethod(
                    selectionMethod
            );

            applicationRepository.save(
                    app
            );

            saveHistory(
                    app,
                    hrUser,
                    "HR_ADMIN",
                    "SELECTION_STARTED",
                    "Selection method: "
                            + selectionMethod
            );
        }


        // =====================================================
        // LOAD FINAL STATUSES
        // =====================================================

        Status selectedStatus =
                statusService.getByName(
                        "SELECTED"
                );

        Status waitlistStatus =
                statusService.getByName(
                        "WAITLIST"
                );

        Status notSelectedStatus =
                statusService.getByName(
                        "NOT_SELECTED"
                );


        // =====================================================
        // TRACK REMAINING ROOMS PER BATCH
        // =====================================================

        Map<Long, Integer> remainingRooms =
                new HashMap<>();


        // =====================================================
        // ALLOCATE
        // =====================================================

        for (Application app : candidates) {

            Batch batch =
                    app.getBatch();


            if (batch == null ||
                    batch.getBatchId() == null) {

                throw new RuntimeException(
                        "Application "
                                + app.getApplicationId()
                                + " has no valid batch"
                );
            }


            Long batchId =
                    batch.getBatchId();


            // -------------------------------------------------
            // LOAD CAPACITY ONCE
            // -------------------------------------------------

            if (!remainingRooms.containsKey(
                    batchId)) {

                Integer numberOfRooms =
                        batch.getNumberOfRooms();

                if (numberOfRooms == null ||
                        numberOfRooms <= 0) {

                    throw new RuntimeException(
                            "Batch "
                                    + batchId
                                    + " has invalid number of rooms"
                    );
                }

                remainingRooms.put(
                        batchId,
                        numberOfRooms
                );
            }


            int roomsAvailable =
                    remainingRooms.get(
                            batchId
                    );


            // -------------------------------------------------
            // REQUESTED ROOMS
            // -------------------------------------------------

            int roomsRequested =
                    app.getRoomsRequested() != null
                            &&
                            app.getRoomsRequested() > 0
                            ?
                            app.getRoomsRequested()
                            :
                            1;


            // =================================================
            // SELECTED
            // =================================================

            if (roomsRequested <= roomsAvailable) {

                app.setStatus(
                        selectedStatus
                );

                app.setSelectedAt(
                        LocalDateTime.now()
                );

                app.setSelectionMethod(
                        selectionMethod
                );

                remainingRooms.put(
                        batchId,
                        roomsAvailable
                                - roomsRequested
                );

                applicationRepository.save(
                        app
                );

                saveHistory(
                        app,
                        hrUser,
                        "HR_ADMIN",
                        "SELECTED",
                        "Application selected using "
                                + selectionMethod
                                + ". Rooms requested: "
                                + roomsRequested
                );

            }


            // =================================================
            // WAITLIST
            // =================================================

            else {

                app.setStatus(
                        waitlistStatus
                );

                app.setSelectionMethod(
                        selectionMethod
                );

                app.setSelectedAt(
                        null
                );

                applicationRepository.save(
                        app
                );

                saveHistory(
                        app,
                        hrUser,
                        "HR_ADMIN",
                        "WAITLISTED",
                        "Application moved to waitlist. "
                                + "Rooms requested: "
                                + roomsRequested
                                + ", rooms remaining: "
                                + roomsAvailable
                );
            }
        }


        // =====================================================
        // FINAL SAVE
        // =====================================================

        applicationRepository.saveAll(
                candidates
        );
    }


    @Transactional
    public void performSelection(
            Long tripId,
            Long batchId,
            String method,
            Employee hrUser) {

        if (method == null ||
                (!"FIFO".equalsIgnoreCase(method)
                        && !"RANDOM".equalsIgnoreCase(method))) {

            throw new RuntimeException(
                    "Selection method must be FIFO or RANDOM"
            );
        }

        String selectionMethod =
                method.trim().toUpperCase();

        // =====================================================
        // GET ONLY APPLICATIONS FOR THIS TRIP + BATCH
        // AND ONLY THOSE APPROVED BY LINE MANAGER
        // =====================================================

        List<Application> candidates =
                new ArrayList<>(
                        applicationRepository
                                .findByTrip_TripIdAndBatch_BatchIdAndStatus_StatusName(
                                        tripId,
                                        batchId,
                                        "APPROVED_BY_MANAGER"
                                )
                );

        if (candidates.isEmpty()) {
            throw new RuntimeException(
                    "No applications ready for selection in the approved batch"
            );
        }

        // =====================================================
        // ORDER
        // =====================================================

        if ("FIFO".equals(selectionMethod)) {

            candidates.sort(
                    Comparator.comparing(
                            Application::getCreatedAt,
                            Comparator.nullsLast(
                                    Comparator.naturalOrder()
                            )
                    )
            );

        } else {

            Collections.shuffle(candidates);
        }

        // =====================================================
        // VERIFY TRIP + BATCH
        // =====================================================

        for (Application app : candidates) {

            if (app.getTrip() == null ||
                    !tripId.equals(
                            app.getTrip().getTripId()
                    )) {

                throw new RuntimeException(
                        "Application does not belong to the selected trip"
                );
            }

            if (app.getBatch() == null ||
                    !batchId.equals(
                            app.getBatch().getBatchId()
                    )) {

                throw new RuntimeException(
                        "Application does not belong to the selected batch"
                );
            }
        }

        // =====================================================
        // LOAD STATUSES
        // =====================================================

        Status inSelectionStatus =
                statusService.getByName("IN_SELECTION");

        Status selectedStatus =
                statusService.getByName("SELECTED");

        Status waitlistStatus =
                statusService.getByName("WAITLIST");

        // =====================================================
        // MARK IN SELECTION
        // =====================================================

        for (Application app : candidates) {

            app.setStatus(inSelectionStatus);

            app.setSelectionMethod(
                    selectionMethod
            );

            applicationRepository.save(app);

            saveHistory(
                    app,
                    hrUser,
                    "HR_ADMIN",
                    "SELECTION_STARTED",
                    "Selection method: "
                            + selectionMethod
                            + ", Batch ID: "
                            + batchId
            );
        }

        // =====================================================
        // BATCH CAPACITY
        // =====================================================

        Batch batch =
                candidates.get(0).getBatch();

        Integer numberOfRooms =
                batch.getNumberOfRooms();

        if (numberOfRooms == null ||
                numberOfRooms <= 0) {

            throw new RuntimeException(
                    "Batch "
                            + batchId
                            + " has invalid number of rooms"
            );
        }

        int remainingRooms =
                numberOfRooms;

        // =====================================================
        // ALLOCATE
        // =====================================================

        for (Application app : candidates) {

            int roomsRequested =
                    app.getRoomsRequested() != null &&
                            app.getRoomsRequested() > 0
                            ? app.getRoomsRequested()
                            : 1;

            if (roomsRequested <= remainingRooms) {

                app.setStatus(selectedStatus);

                app.setSelectedAt(
                        LocalDateTime.now()
                );

                app.setSelectionMethod(
                        selectionMethod
                );

                remainingRooms -= roomsRequested;

                applicationRepository.save(app);

                saveHistory(
                        app,
                        hrUser,
                        "HR_ADMIN",
                        "SELECTED",
                        "Application selected using "
                                + selectionMethod
                                + ". Rooms requested: "
                                + roomsRequested
                );

            } else {

                app.setStatus(waitlistStatus);

                app.setSelectionMethod(
                        selectionMethod
                );

                app.setSelectedAt(null);

                applicationRepository.save(app);

                saveHistory(
                        app,
                        hrUser,
                        "HR_ADMIN",
                        "WAITLISTED",
                        "Application moved to waitlist. "
                                + "Rooms requested: "
                                + roomsRequested
                                + ", rooms remaining: "
                                + remainingRooms
                );
            }
        }

        applicationRepository.saveAll(candidates);
    }

    // =========================================================
    // COMMON - GET APPLICATION
    // =========================================================

    public Application getApplicationById(

            Long applicationId,
            Employee employee) {

        Application application =
                applicationRepository
                        .findById(applicationId)
                        .orElseThrow(() ->
                                new RuntimeException(
                                        "Application not found"
                                )
                        );


        // =====================================================
        // OWNER
        // =====================================================

        if (application.getEmployee() != null &&
                application.getEmployee()
                        .getEmployeeId()
                        .equals(
                                employee.getEmployeeId()
                        )) {

            return application;
        }


        // =====================================================
        // LINE MANAGER
        //
        // A manager can access an application only if the
        // application's employee reports directly to him.
        // =====================================================

        if ("LINE_MANAGER".equalsIgnoreCase(
                getEmployeeRole(employee))) {

            Employee applicationEmployee =
                    application.getEmployee();

            if (applicationEmployee != null &&
                    applicationEmployee.getManager() != null &&
                    applicationEmployee
                            .getManager()
                            .getEmployeeId()
                            .equals(
                                    employee.getEmployeeId()
                            )) {

                return application;
            }
        }


        throw new RuntimeException(
                "Access denied. You are not allowed to access this application."
        );
    }


